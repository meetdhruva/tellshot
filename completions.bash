    COMPREPLY=()
    if [[ "${BASH_VERSINFO[0]}" -ge 4 ]]; then
        cur="$2"
    else
        cur="${COMP_WORDS[COMP_CWORD]}"
    fi
    prev="$3"
    cmd=""
    opts=""

    for i in "${COMP_WORDS[@]:0:COMP_CWORD}"
    do
        case "${cmd},${i}" in
            ",$1")
                cmd="tellshot"
                ;;
            tellshot,capture)
                cmd="tellshot__subcmd__capture"
                ;;
            tellshot,completions)
                cmd="tellshot__subcmd__completions"
                ;;
