                cmd="tellshot__subcmd__help__subcmd__targets"
                ;;
            *)
                ;;
        esac
    done

    case "${cmd}" in
        tellshot)
            opts="-h -V --json --help --version targets capture new describe edit export stitch schema mcp completions help"
